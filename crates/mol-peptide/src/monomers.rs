#![forbid(unsafe_code)]

//! Curated atomic monomer catalog for canonical L/D amino acids, N-methylated & backbone-modified
//! peptidomimetics, authentic NRPS non-proteinogenic building blocks, depsipeptide α-hydroxy acids,
//! stapling/click monomers, and N-/C-terminal caps & fatty-acyl starters.
//!
//! Each monomer is defined via an isotope-tagged SMILES template:
//! - `[101N]` / `[101O]`: N-terminal attachment atom (amide N or depsipeptide ester O)
//! - `[102C]`: α-carbon (stereocenter flipped for D-isomers)
//! - `[103C]`: backbone carbonyl carbon `C=O`
//! - `[104O]`: leaving carboxyl `-OH` removed upon peptide/ester/cyclization condensation
//! - `[105*]`: sidechain reactive anchor (`O` lactone, `N` lactam, `S` disulfide/lanthionine,
//!   `C` carboxyl/alkene/alkyne)
//! - `[106*]`: sidechain leaving group (`O` of Asp/Glu/Aad COOH, terminal `=CH2` of S5/R8,
//!   terminal `#CH` of Pra)
//!
//! Custom user monomers can be loaded at runtime from `$CRAFT_DATA_DIR/monomers/*.json`.

use std::path::Path;

use serde::{Deserialize, Serialize};

/// Broad chemical / biosynthetic category for UI grouping and developability scoring.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum MonomerClass {
    Canonical,
    BackboneModified,
    Depsipeptide,
    NrpsCationic,
    NrpsAromatic,
    NrpsAliphaticSpecial,
    Heterocycle,
    StaplingClick,
    Custom,
}

impl MonomerClass {
    pub fn label(self) -> &'static str {
        match self {
            Self::Canonical => "Canonical AA",
            Self::BackboneModified => "Backbone / α,α / β",
            Self::Depsipeptide => "Depsipeptide (α-OH)",
            Self::NrpsCationic => "NRPS Cationic",
            Self::NrpsAromatic => "NRPS Aromatic",
            Self::NrpsAliphaticSpecial => "NRPS Aliphatic / Special",
            Self::Heterocycle => "NRPS Heterocycle (Cy/Ox)",
            Self::StaplingClick => "Stapling & Click",
            Self::Custom => "Custom",
        }
    }
}

/// Sidechain functional reactivity for cross-links & cyclizations.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum SidechainAnchorKind {
    None,
    Hydroxyl,
    Amine,
    Thiol,
    Carboxyl,
    AlkeneStaple,
    Dehydro,
    AlkyneClick,
    AzideClick,
}

/// Curated atomic monomer specification.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MonomerSpec {
    pub code: String,
    pub aliases: Vec<String>,
    pub one_letter: Option<char>,
    pub pdb_code: String,
    pub helm_symbol: String,
    pub name: String,
    pub class: MonomerClass,
    /// Isotope-tagged free-acid SMILES (L-configuration when chiral).
    pub smiles_template: String,
    pub has_alpha_chiral: bool,
    pub is_tertiary_n: bool,
    pub is_hydroxy_acid: bool,
    pub anchor_kind: SidechainAnchorKind,
    /// Approximate sidechain charge at pH 7.4 (for fast sequence-level estimates).
    pub charge_ph74: f64,
    /// Sidechain pKa for exact Henderson-Hasselbalch pI calculation: `Some((pka, is_acidic))`.
    pub sidechain_pka: Option<(f64, bool)>,
    /// Kyte-Doolittle / Wimley-White-like hydrophobicity scale (`-4.5` hydrophilic .. `+4.5` lipophilic).
    pub hydropathy: f64,
    pub is_hydrophobic: bool,
    pub bulky_coupling: bool,
}

/// N-terminal cap or fatty-acyl NRPS starter unit.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NCapSpec {
    pub code: String,
    pub aliases: Vec<String>,
    pub pdb_code: String,
    pub helm_symbol: String,
    pub name: String,
    /// Free carboxylic acid SMILES with `[103C](=O)[104O]`; empty string denotes free `H-`.
    pub smiles_template: String,
    pub is_lipid: bool,
}

/// C-terminal modification / cap.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Default)]
pub enum CCapKind {
    #[default]
    FreeAcid,
    Amide,
    Alcohol,
    Aldehyde,
    MethylEster,
    EthylAmide,
}

impl CCapKind {
    pub fn code(self) -> &'static str {
        match self {
            Self::FreeAcid => "OH",
            Self::Amide => "NH2",
            Self::Alcohol => "ol",
            Self::Aldehyde => "CHO",
            Self::MethylEster => "OMe",
            Self::EthylAmide => "NHEt",
        }
    }

    pub fn helm_symbol(self) -> &'static str {
        match self {
            Self::FreeAcid => "",
            Self::Amide => "[am]",
            Self::Alcohol => "[ol]",
            Self::Aldehyde => "[al]",
            Self::MethylEster => "[OMe]",
            Self::EthylAmide => "[NHEt]",
        }
    }

    pub fn parse_suffix(tok: &str) -> Option<Self> {
        match tok.trim().to_ascii_lowercase().as_str() {
            "oh" | "cooh" => Some(Self::FreeAcid),
            "nh2" | "am" | "amide" => Some(Self::Amide),
            "ol" | "ch2oh" => Some(Self::Alcohol),
            "cho" | "al" | "h" => Some(Self::Aldehyde),
            "ome" | "och3" => Some(Self::MethylEster),
            "nhet" => Some(Self::EthylAmide),
            _ => None,
        }
    }
}

/// Complete runtime catalog of monomers and N-terminal caps.
#[derive(Debug, Clone)]
pub struct MonomerCatalog {
    pub monomers: Vec<MonomerSpec>,
    pub n_caps: Vec<NCapSpec>,
}

#[allow(clippy::too_many_arguments)]
fn mk(
    code: &str,
    aliases: &[&str],
    one_letter: Option<char>,
    pdb_code: &str,
    helm_symbol: &str,
    name: &str,
    class: MonomerClass,
    smiles_template: &str,
    has_alpha_chiral: bool,
    is_tertiary_n: bool,
    is_hydroxy_acid: bool,
    anchor_kind: SidechainAnchorKind,
    charge_ph74: f64,
    sidechain_pka: Option<(f64, bool)>,
    hydropathy: f64,
    is_hydrophobic: bool,
    bulky_coupling: bool,
) -> MonomerSpec {
    MonomerSpec {
        code: code.to_string(),
        aliases: aliases.iter().map(|s| (*s).to_string()).collect(),
        one_letter,
        pdb_code: pdb_code.to_string(),
        helm_symbol: helm_symbol.to_string(),
        name: name.to_string(),
        class,
        smiles_template: smiles_template.to_string(),
        has_alpha_chiral,
        is_tertiary_n,
        is_hydroxy_acid,
        anchor_kind,
        charge_ph74,
        sidechain_pka,
        hydropathy,
        is_hydrophobic,
        bulky_coupling,
    }
}

fn cap(
    code: &str,
    aliases: &[&str],
    pdb_code: &str,
    helm_symbol: &str,
    name: &str,
    smiles_template: &str,
    is_lipid: bool,
) -> NCapSpec {
    NCapSpec {
        code: code.to_string(),
        aliases: aliases.iter().map(|s| (*s).to_string()).collect(),
        pdb_code: pdb_code.to_string(),
        helm_symbol: helm_symbol.to_string(),
        name: name.to_string(),
        smiles_template: smiles_template.to_string(),
        is_lipid,
    }
}

