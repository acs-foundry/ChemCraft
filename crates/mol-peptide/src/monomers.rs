    /// Load optional user-defined custom monomers from JSON files in `$CRAFT_DATA_DIR/monomers/`.
    pub fn load_custom_dir(&mut self, dir: &Path) -> usize {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return 0;
        };
        let mut loaded = 0usize;
        for entry in entries.flatten() {
            let p = entry.path();
            if p.extension().and_then(|s| s.to_str()) != Some("json") {
                continue;
            }
            if let Ok(text) = std::fs::read_to_string(&p)
                && let Ok(list) = serde_json::from_str::<Vec<MonomerSpec>>(&text)
            {
                for mut m in list {
                    m.class = MonomerClass::Custom;
                    self.monomers.push(m);
                    loaded += 1;
                }
            }
        }
        loaded
    }

    /// Look up a base monomer by code, alias, HELM symbol, or 1-letter code (case-insensitive).
    pub fn find_monomer(&self, token: &str) -> Option<&MonomerSpec> {
        let t = token.trim();
        if t.is_empty() {
            return None;
        }
        if t.len() == 1
            && let Some(ch) = t.chars().next()
        {
            let cu = ch.to_ascii_uppercase();
            if let Some(m) = self.monomers.iter().find(|m| m.one_letter == Some(cu)) {
                return Some(m);
            }
        }
        self.monomers.iter().find(|m| {
            m.code.eq_ignore_ascii_case(t)
                || m.helm_symbol.eq_ignore_ascii_case(t)
                || m.pdb_code.eq_ignore_ascii_case(t)
                || m.aliases.iter().any(|a| a.eq_ignore_ascii_case(t))
        })
    }

    /// Look up an N-terminal cap or lipid starter by code, alias, or HELM tag.
    pub fn find_n_cap(&self, token: &str) -> Option<&NCapSpec> {
        let t = token.trim().trim_matches(['[', ']']);
        if t.is_empty() {
            return None;
        }
        self.n_caps.iter().find(|c| {
            c.code.eq_ignore_ascii_case(t)
                || c.helm_symbol
                    .trim_matches(['[', ']'])
                    .eq_ignore_ascii_case(t)
                || c.aliases.iter().any(|a| a.eq_ignore_ascii_case(t))
        })
    }

    /// Total number of distinct monomer entries (including D-enantiomers of chiral residues).
    #[must_use]
    pub fn total_stereomonomer_count(&self) -> usize {
        self.monomers
            .iter()
            .map(|m| if m.has_alpha_chiral { 2 } else { 1 })
            .sum()
    }
